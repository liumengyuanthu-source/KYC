// Deterministic, allowlisted copy of the user-approved frozen sample. No downloads.
import {readFile,writeFile,mkdir,copyFile,readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const source=new URL('../../../experiments/d2-batch-a-media/',import.meta.url);
const destination=new URL('./d2-batch-a/r01/',import.meta.url);
const hash=b=>createHash('sha256').update(b).digest('hex');
const selection=JSON.parse(await readFile(new URL('integration-selection.json',source)));
for(const file of selection.source_manifests){if(hash(await readFile(new URL(file.path,source)))!==file.sha256)throw Error(`Selection hash mismatch: ${file.path}`);}
const files=['src/content.js','src/views.js','src/player.js','styles/media.css','integration-selection.json','MAINLINE_INTEGRATION_HANDOFF.md','source/cue-manifest.json','source/diagram-contract.json','source/image-generation.md','source/Clear_to_Trade_D2_Batch_A_Scope_Entity_Final_v1.0.md','source/Clear_to_Trade_D2_Batch_A_Media_Format_and_Demo_Brief_v1.0.md',...selection.source_manifests.map(x=>x.path)];
for(const locale of ['zh-CN','en-AU','en-US']){
 files.push(`locales/${locale}.json`);
 for(const asset of ['DMO-A01','DMO-A02'])files.push(`print/${asset}__r01__${locale}.html`,`assets/posters/${asset}__panel-first__r01__${locale}__C1.png`);
}
for(const p of await readdir(new URL('assets/personas/',source)))if(p.endsWith('.webp'))files.push(`assets/personas/${p}`);
for(const kind of ['DG-SCOPE-A','DG-ENTITY-A','DG-ENABLE-A'])for(const locale of ['zh-CN','en-AU']){
 files.push(`source/diagrams/${kind}__r01__${locale}.json`);
 for(const ext of ['svg','html'])files.push(`assets/diagrams/${kind}__r01__${locale}.${ext}`);
}
const records=[];
for(const file of [...new Set(files)].sort()){
 const src=new URL(file,source),dst=new URL(file,destination),bytes=await readFile(src);
 await mkdir(path.dirname(fileURLToPath(dst)),{recursive:true});await copyFile(src,dst);
 if(hash(await readFile(dst))!==hash(bytes))throw Error(`Copy verification failed: ${file}`);
 records.push({path:file,sha256:hash(bytes),bytes:bytes.length});
}
await writeFile(new URL('package-provenance.json',destination),JSON.stringify({selection_status:selection.selection_status,source:'experiments/d2-batch-a-media',runtime_origin:'same_origin_only',revision:'r01',files:records},null,2)+'\n');
// Embed frozen text outside the optional media package. Blocking all media URLs
// must not prevent the host or its complete text/print fallback from loading.
const {contract,cues}=await import(new URL('src/content.js',source));const locales={};
for(const l of ['zh-CN','en-AU','en-US'])locales[l]=JSON.parse(await readFile(new URL(`locales/${l}.json`,source)));
await writeFile(new URL('../batch-a-media-story.mjs',import.meta.url),'// Generated by media/build-batch-a-r01.mjs from approved r01; do not hand edit.\nexport const story='+JSON.stringify({contract,cues,locales})+';\n');
console.log(JSON.stringify({copied:records.length,bytes:records.reduce((n,r)=>n+r.bytes,0),selection_hashes_verified:selection.source_manifests.length}));
